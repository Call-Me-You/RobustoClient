        {
            if (_entMan.EntitySysManager.TryGetEntitySystem<RobustoClient.Systems.Construction.RobustaAutoConstructSystem>(out var autoSys))
                autoSys.StopJob();
        };
        ExportBlueprintBtn.OnPressed += _ =>
        {
            if (_entMan.EntitySysManager.TryGetEntitySystem<RobustoClient.Systems.Construction.Blueprints.RobustaBlueprintManager>(out var bpMan))
                bpMan.StartAreaExportSelection(BlueprintExportNameInput.Text);
        };
        ReloadBlueprintsBtn.OnPressed += _ =>
        {
            if (_entMan.EntitySysManager.TryGetEntitySystem<RobustoClient.Systems.Construction.Blueprints.RobustaBlueprintManager>(out var bpMan))
                bpMan.LoadAllBlueprints();
        };

        ApplyBindsBtn.OnPressed += _ => ApplyCustomBinds();

        // Ping Handlers
        PingLocal.OnPressed += _ => SetPingMode(RobustaConfig.PingMode.Local);
        PingStable.OnPressed += _ => SetPingMode(RobustaConfig.PingMode.Stable);
        PingLaggy.OnPressed += _ => SetPingMode(RobustaConfig.PingMode.Laggy);
        PingAuto.OnPressed += _ => SetPingMode(RobustaConfig.PingMode.Auto);
        UpdatePingButtons();

        // Tab Navigation
        TabCombat.OnPressed += _ => ShowSection(CombatSection);
        TabVisuals.OnPressed += _ => ShowSection(VisualsSection);
        TabUtility.OnPressed += _ => ShowSection(UtilitySection);
        TabBinds.OnPressed += _ => ShowSection(BindsSection);

        // Default view
        ShowSection(CombatSection);
    }

    private static bool TryParseKey(string input, out Keyboard.Key key)
    {
        key = Keyboard.Key.Unknown;
        var text = input.Trim();
        if (string.IsNullOrEmpty(text))
            return false;

        switch (text.ToLowerInvariant())
        {
            case ".":
            case "dot":
            case "period":
                key = Keyboard.Key.Period;
                return true;
            case ",":
            case "comma":
                key = Keyboard.Key.Comma;
                return true;
            case "/":
            case "slash":
                key = Keyboard.Key.Slash;
                return true;
            case "\\":
            case "backslash":
                key = Keyboard.Key.BackSlash;
                return true;
            case ";":
            case "semicolon":
                key = Keyboard.Key.SemiColon;
                return true;
            case "'":
            case "\"":
            case "apostrophe":
            case "quote":
                key = Keyboard.Key.Apostrophe;
                return true;
            case "[":
            case "lbracket":
            case "bracketleft":
                key = Keyboard.Key.LBracket;
                return true;
            case "]":
            case "rbracket":
            case "bracketright":
                key = Keyboard.Key.RBracket;
                return true;
            case "`":
            case "~":
            case "tilde":
            case "grave":
                key = Keyboard.Key.Tilde;
                return true;
            case "=":
            case "equal":
            case "equals":
                key = Keyboard.Key.Equal;
                return true;
            case "-":
            case "minus":
            case "subtract":
                key = Keyboard.Key.Minus;
                return true;
            case "+":
            case "plus":
            case "add":
                key = Keyboard.Key.NumpadAdd;
                return true;
            case "enter":
            case "return":
                key = Keyboard.Key.Return;
                return true;
            case "esc":
            case "escape":
                key = Keyboard.Key.Escape;
                return true;
            case "ctrl":
            case "control":
                key = Keyboard.Key.Control;
                return true;
            case "back":
            case "backspace":
                key = Keyboard.Key.BackSpace;
                return true;
            case "del":
            case "delete":
                key = Keyboard.Key.Delete;
                return true;
            case "ins":
            case "insert":
                key = Keyboard.Key.Insert;
                return true;
            case "pgup":
            case "pageup":
                key = Keyboard.Key.PageUp;
                return true;
            case "pgdn":
            case "pagedown":
                key = Keyboard.Key.PageDown;
                return true;
            case "space":
            case "spacebar":
                key = Keyboard.Key.Space;
                return true;
        }

        if (Enum.TryParse<Keyboard.Key>(text, true, out var parsed) && parsed != Keyboard.Key.Unknown)
        {
            key = parsed;
            return true;
        }

        return false;
    }

    private void ApplyCustomBinds()
    {
        bool valid = true;
        Keyboard.Key newBuild = RobustaConfig.AutoConstructKey;
        Keyboard.Key newDecon = RobustaConfig.AutoDeconstructKey;
        Keyboard.Key newLock = RobustaConfig.TargetLockKey;

        if (TryParseKey(BindBuildInput.Text, out var parsedBuild))
            newBuild = parsedBuild;
        else
            valid = false;

        if (TryParseKey(BindDeconstructInput.Text, out var parsedDecon))
            newDecon = parsedDecon;
        else
            valid = false;

        if (TryParseKey(BindTargetLockInput.Text, out var parsedLock))
            newLock = parsedLock;
        else
            valid = false;

        if (!valid)
        {
            BindStatusLabel.Text = "Invalid key name(s). Use standard names or symbols (e.g. Period / ., Comma / ,, Space).";
            BindStatusLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#FF6B6B");
            return;
        }

        RobustaConfig.AutoConstructKey = newBuild;
        RobustaConfig.AutoDeconstructKey = newDecon;
        RobustaConfig.TargetLockKey = newLock;
        RobustaConfig.Save();

        BindStatusLabel.Text = "Keybinds updated and saved successfully!";
        BindStatusLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#40FF40");
    }

    protected override void FrameUpdate(Robust.Shared.Timing.FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_savePending)
        {
            _saveDebounceTimer -= args.DeltaSeconds;
            if (_saveDebounceTimer <= 0f)
            {
                FlushPendingSave();
            }
        }
    }

    private void SetPingMode(RobustaConfig.PingMode mode)
    {
        RobustaConfig.CurrentPingMode = mode;
        RobustaConfig.Save();
        Robust.Shared.Log.Logger.GetSawmill("RobustaAim").Info($"> Ping Mode set to: {mode}");
        UpdatePingButtons();
    }

    private void UpdatePingButtons()
    {
        // Safe style removal for cross-version compatibility
        string[] colors = { "ButtonColorGreen", "ButtonColorRed" };
        foreach (var color in colors)
        {
            PingLocal.RemoveStyleClass(color);
            PingStable.RemoveStyleClass(color);
            PingLaggy.RemoveStyleClass(color);
            PingAuto.RemoveStyleClass(color);
        }

        switch (RobustaConfig.CurrentPingMode)
        {
            case RobustaConfig.PingMode.Local: PingLocal.AddStyleClass("ButtonColorGreen"); break;
            case RobustaConfig.PingMode.Stable: PingStable.AddStyleClass("ButtonColorGreen"); break;
            case RobustaConfig.PingMode.Laggy: PingLaggy.AddStyleClass("ButtonColorGreen"); break;
            case RobustaConfig.PingMode.Auto: PingAuto.AddStyleClass("ButtonColorGreen"); break;
        }
    }

    private void ShowSection(Control section)
    {
        CombatSection.Visible = (section == CombatSection);
        VisualsSection.Visible = (section == VisualsSection);
        UtilitySection.Visible = (section == UtilitySection);
        BindsSection.Visible = (section == BindsSection);

        // Safe style removal
        TabCombat.RemoveStyleClass("ButtonColorGreen");
        TabVisuals.RemoveStyleClass("ButtonColorGreen");
        TabUtility.RemoveStyleClass("ButtonColorGreen");
        TabBinds.RemoveStyleClass("ButtonColorGreen");

        // Safe style addition
        if (section == CombatSection) TabCombat.AddStyleClass("ButtonColorGreen");
        if (section == VisualsSection) TabVisuals.AddStyleClass("ButtonColorGreen");
        if (section == UtilitySection) TabUtility.AddStyleClass("ButtonColorGreen");
        if (section == BindsSection) TabBinds.AddStyleClass("ButtonColorGreen");
    }
